def portfolio_table():
    rows = []
    for g in GAMES:
        c = model.costs(g)
        rows.append(
            (
                g["id"],
                g["ar"],
                g["category"],
                game_docs.players_txt(g),
                f"{g['reset']['time_s']} ث",
                fmt(c["rec"]["total"]),
                model.weighted_score(g),
            )
        )
    return table(
        [
            "الرمز",
            "اللعبة",
            "الفئة",
            "اللاعبون",
            "الإعادة",
            "الموصى بها (ريال)",
            "النتيجة",
        ],
        rows,
        num_cols=(5, 6),
    )


